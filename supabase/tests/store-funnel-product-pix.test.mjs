import assert from 'node:assert/strict';
import fs from 'node:fs';
const loja = fs.readFileSync('loja.html', 'utf8');
const painel = fs.readFileSync('painel.html', 'utf8');
const migration = fs.readFileSync('supabase/migrations/20261122170000_store_funnel_product_view_pix_generated.sql', 'utf8');
assert.match(loja, /feira_funnel_product_views_v1/, 'product views are remembered only in sessionStorage');
assert.match(loja, /sessionStorage\.getItem\('feira_funnel_product_views_v1'/, 'session product view state is restored');
assert.match(loja, /closest\('\.product\[data-product-id\]'\)/, 'tapping a product card identifies its product');
assert.match(loja, /productViews\.has\(productId\)/, 'a product is counted at most once per session');
assert.match(loja, /record\('product_view'\)/, 'product_view uses the existing anonymous funnel RPC');
assert.match(loja, /result\.includes\('pix gerado'\)/, 'Pix event waits for the generated Pix screen text');
assert.match(loja, /record\('pix_generated'(?:,|\))/, 'pix_generated records the elapsed generation time through the anonymous funnel RPC');
assert.match(painel, /\['visit','Visitas'\],\['product_view','Viu produto'\],\['add_to_cart','Carrinho'\]/, 'funnel starts with visits, product views and cart');
assert.match(painel, /\['checkout_open','Checkout'\],\['pix_generated','Pix gerado'\],\['order_paid','Pago'\]/, 'funnel ends with checkout, generated Pix and paid');
assert.match(migration, /'product_view'.*'add_to_cart'/s, 'database accepts product_view');
assert.match(migration, /'pix_generated'.*'order_paid'/s, 'database accepts pix_generated');
assert.match(migration, /public\.is_current_user_admin\(\)/, 'admins remain excluded');
assert.match(migration, /feira_cost_private\.customer_test_accounts/, 'test accounts remain excluded');
assert.match(migration, /SECURITY DEFINER SET search_path = ''/, 'existing hardened RPC execution model is preserved');
assert.match(migration, /GRANT EXECUTE ON FUNCTION public\.record_store_funnel_event[^;]* TO anon, authenticated/s, 'existing RPC roles can record events');
assert.doesNotMatch(loja, /document\.cookie/, 'no cookie tracking is introduced');
console.log('Store funnel product and Pix event tests passed.');

-- Parte 4b: margem automática e revisão de preços. Não altera preços na instalação.
CREATE TABLE IF NOT EXISTS feira_cost_private.automatic_margin_settings (
  settings_key text PRIMARY KEY DEFAULT 'default' CHECK (settings_key='default'),
  tiers jsonb NOT NULL DEFAULT '{"up_to_25":2,"from_25_to_50":4,"from_50_to_100":8,"above_100":12}'::jsonb,
  auto_apply boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid
);
INSERT INTO feira_cost_private.automatic_margin_settings(settings_key)
VALUES ('default') ON CONFLICT (settings_key) DO NOTHING;
ALTER TABLE feira_cost_private.automatic_margin_settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE feira_cost_private.automatic_margin_settings FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE feira_cost_private.automatic_margin_settings TO service_role;

CREATE TABLE IF NOT EXISTS feira_cost_private.product_sale_price_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL,
  old_price numeric(12,2) NOT NULL,
  new_price numeric(12,2) NOT NULL,
  changed_by uuid,
  changed_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE feira_cost_private.product_sale_price_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE feira_cost_private.product_sale_price_history FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE feira_cost_private.product_sale_price_history TO service_role;
CREATE INDEX IF NOT EXISTS product_sale_price_history_product_changed_idx
  ON feira_cost_private.product_sale_price_history(product_id, changed_at DESC);

CREATE OR REPLACE FUNCTION feira_cost_private.suggested_sale_price(p_balcony numeric, p_tiers jsonb)
RETURNS numeric
LANGUAGE plpgsql IMMUTABLE
SET search_path TO ''
AS $function$
DECLARE v_margin numeric;
BEGIN
  IF p_balcony IS NULL OR p_balcony < 0 THEN RETURN NULL; END IF;
  v_margin := CASE
    WHEN p_balcony <= 25 THEN (p_tiers->>'up_to_25')::numeric
    WHEN p_balcony <= 50 THEN (p_tiers->>'from_25_to_50')::numeric
    WHEN p_balcony <= 100 THEN (p_tiers->>'from_50_to_100')::numeric
    ELSE (p_tiers->>'above_100')::numeric
  END;
  -- Menor preço com centavos ,99 que não fica abaixo de balcão + margem.
  RETURN round((ceil((p_balcony + v_margin) - 0.99) + 0.99)::numeric, 2);
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_get_automatic_margin_settings()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_result jsonb;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_current_user_admin() THEN
    RAISE EXCEPTION 'Acesso permitido somente a administradores.' USING ERRCODE='42501';
  END IF;
  SELECT jsonb_build_object('tiers',s.tiers,'auto_apply',s.auto_apply,'updated_at',s.updated_at)
    INTO v_result
  FROM feira_cost_private.automatic_margin_settings s WHERE s.settings_key='default';
  RETURN COALESCE(v_result,'{"tiers":{"up_to_25":2,"from_25_to_50":4,"from_50_to_100":8,"above_100":12},"auto_apply":false}'::jsonb);
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_save_automatic_margin_settings(p_tiers jsonb, p_auto_apply boolean)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_key text; v_value numeric;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_current_user_admin() THEN
    RAISE EXCEPTION 'Acesso permitido somente a administradores.' USING ERRCODE='42501';
  END IF;
  IF jsonb_typeof(p_tiers) IS DISTINCT FROM 'object'
     OR NOT (p_tiers ?& ARRAY['up_to_25','from_25_to_50','from_50_to_100','above_100']) THEN
    RAISE EXCEPTION 'Informe as quatro margens.' USING ERRCODE='22023';
  END IF;
  FOREACH v_key IN ARRAY ARRAY['up_to_25','from_25_to_50','from_50_to_100','above_100'] LOOP
    BEGIN v_value := (p_tiers->>v_key)::numeric;
    EXCEPTION WHEN OTHERS THEN RAISE EXCEPTION 'Margem inválida: %.',v_key USING ERRCODE='22023'; END;
    IF v_value < 0 OR v_value > 100000 THEN
      RAISE EXCEPTION 'Margens devem ser valores não negativos.' USING ERRCODE='22023';
    END IF;
  END LOOP;
  INSERT INTO feira_cost_private.automatic_margin_settings(settings_key,tiers,auto_apply,updated_at,updated_by)
  VALUES('default',p_tiers,p_auto_apply,now(),auth.uid())
  ON CONFLICT(settings_key) DO UPDATE SET tiers=EXCLUDED.tiers,auto_apply=EXCLUDED.auto_apply,updated_at=now(),updated_by=auth.uid();
  RETURN jsonb_build_object('success',true,'tiers',p_tiers,'auto_apply',p_auto_apply);
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_get_automatic_price_review()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_tiers jsonb; v_products jsonb; v_missing jsonb;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_current_user_admin() THEN
    RAISE EXCEPTION 'Acesso permitido somente a administradores.' USING ERRCODE='42501';
  END IF;
  SELECT tiers INTO v_tiers FROM feira_cost_private.automatic_margin_settings WHERE settings_key='default';
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'id',p.id,'name',p.name,'unit',COALESCE(to_jsonb(p)->>'sale_unit','un'),
    'balcony',pc.preco_balcao,'current_price',p.price,
    'suggested_price',CASE WHEN p.old_price IS NULL THEN feira_cost_private.suggested_sale_price(pc.preco_balcao,v_tiers) ELSE NULL END,
    'is_promo',p.old_price IS NOT NULL,
    'difference',CASE WHEN p.old_price IS NULL THEN round(feira_cost_private.suggested_sale_price(pc.preco_balcao,v_tiers)-p.price,2) ELSE NULL END,
    'real_profit',CASE WHEN p.old_price IS NULL THEN round(feira_cost_private.suggested_sale_price(pc.preco_balcao,v_tiers)-COALESCE(pc.preco_pago,pc.preco_balcao),2) ELSE NULL END
  ) ORDER BY p.name),'[]'::jsonb) INTO v_products
  FROM public.products p JOIN feira_cost_private.product_costs pc ON pc.product_id=p.id
  WHERE pc.preco_balcao IS NOT NULL;
  SELECT COALESCE(jsonb_agg(jsonb_build_object('id',p.id,'name',p.name,'current_price',p.price) ORDER BY p.name),'[]'::jsonb)
    INTO v_missing
  FROM public.products p
  LEFT JOIN feira_cost_private.product_costs pc ON pc.product_id=p.id
  WHERE pc.preco_balcao IS NULL;
  RETURN jsonb_build_object('products',v_products,'without_balcony',v_missing);
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_apply_automatic_price(p_product_id text)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_product public.products%ROWTYPE; v_balcony numeric; v_tiers jsonb; v_suggested numeric; v_actor uuid:=auth.uid();
BEGIN
  IF v_actor IS NULL OR NOT public.is_current_user_admin() THEN
    RAISE EXCEPTION 'Acesso permitido somente a administradores.' USING ERRCODE='42501';
  END IF;
  SELECT * INTO v_product FROM public.products WHERE id=p_product_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Produto não encontrado.' USING ERRCODE='P0002'; END IF;
  IF v_product.old_price IS NOT NULL THEN
    RAISE EXCEPTION 'Produto em promoção: preço de venda preservado.' USING ERRCODE='22023';
  END IF;
  SELECT pc.preco_balcao INTO v_balcony FROM feira_cost_private.product_costs pc WHERE pc.product_id=p_product_id;
  IF v_balcony IS NULL THEN RAISE EXCEPTION 'Produto sem preço de balcão.' USING ERRCODE='22023'; END IF;
  SELECT tiers INTO v_tiers FROM feira_cost_private.automatic_margin_settings WHERE settings_key='default';
  v_suggested:=feira_cost_private.suggested_sale_price(v_balcony,v_tiers);
  IF v_product.price IS DISTINCT FROM v_suggested THEN
    INSERT INTO feira_cost_private.product_sale_price_history(product_id,old_price,new_price,changed_by)
    VALUES(p_product_id,v_product.price,v_suggested,v_actor);
    UPDATE public.products SET price=v_suggested WHERE id=p_product_id;
  END IF;
  RETURN jsonb_build_object('success',true,'product_id',p_product_id,'old_price',v_product.price,'new_price',v_suggested);
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_apply_all_automatic_prices()
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_row record; v_result jsonb; v_applied integer:=0; v_skipped_promo integer:=0; v_unchanged integer:=0;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_current_user_admin() THEN
    RAISE EXCEPTION 'Acesso permitido somente a administradores.' USING ERRCODE='42501';
  END IF;
  FOR v_row IN
    SELECT p.id,p.old_price,p.price,pc.preco_balcao
    FROM public.products p JOIN feira_cost_private.product_costs pc ON pc.product_id=p.id
    WHERE pc.preco_balcao IS NOT NULL ORDER BY p.id
  LOOP
    IF v_row.old_price IS NOT NULL THEN
      v_skipped_promo:=v_skipped_promo+1;
    ELSE
      v_result:=public.admin_apply_automatic_price(v_row.id);
      IF (v_result->>'old_price')::numeric IS DISTINCT FROM (v_result->>'new_price')::numeric THEN
        v_applied:=v_applied+1;
      ELSE v_unchanged:=v_unchanged+1; END IF;
    END IF;
  END LOOP;
  RETURN jsonb_build_object('success',true,'applied',v_applied,'skipped_promo',v_skipped_promo,'unchanged',v_unchanged);
END;
$function$;


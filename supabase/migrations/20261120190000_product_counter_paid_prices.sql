CREATE OR REPLACE FUNCTION feira_cost_private.capture_order_item_costs()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_item jsonb;
  v_index integer;
  v_item_count integer := 0;
  v_product_id text;
  v_product_name text;
  v_quantity numeric;
  v_sale_unit_price numeric;
  v_unit_cost numeric;
  v_preco_balcao numeric;
  v_preco_pago numeric;
  v_sale_total numeric;
  v_cost_total numeric;
  v_existing feira_cost_private.order_item_snapshots%ROWTYPE;
  v_has_existing boolean;
  v_error text;
BEGIN
  BEGIN
    IF jsonb_typeof(NEW.items) = 'array' THEN
      FOR v_item, v_index IN
        SELECT item.value, (item.ordinality - 1)::integer
        FROM jsonb_array_elements(NEW.items) WITH ORDINALITY AS item(value, ordinality)
      LOOP
        v_item_count := v_item_count + 1;
        v_product_id := NULLIF(v_item->>'id', '');
        v_product_name := COALESCE(NULLIF(v_item->>'name', ''), 'Produto sem nome');
        v_quantity := COALESCE(NULLIF(v_item->>'qty', ''), NULLIF(v_item->>'quantity', ''))::numeric;
        v_sale_unit_price := NULLIF(v_item->>'price', '')::numeric;

        SELECT * INTO v_existing
        FROM feira_cost_private.order_item_snapshots
        WHERE order_id=NEW.id AND item_index=v_index;
        v_has_existing := FOUND AND v_existing.product_id IS NOT DISTINCT FROM v_product_id;

        IF v_has_existing THEN
          -- Mantém os preços fotografados anteriormente; alterações no catálogo não reescrevem pedidos antigos.
          v_preco_balcao := v_existing.preco_balcao;
          v_preco_pago := v_existing.preco_pago;
          v_unit_cost := COALESCE(v_existing.preco_pago,v_existing.preco_balcao,v_existing.unit_cost);
        ELSE
          v_preco_balcao := NULL;
          v_preco_pago := NULL;
          v_unit_cost := NULL;
          IF v_product_id IS NOT NULL THEN
            SELECT pc.preco_balcao,pc.preco_pago
              INTO v_preco_balcao,v_preco_pago
            FROM feira_cost_private.product_costs pc
            WHERE pc.product_id=v_product_id;
            v_unit_cost := COALESCE(v_preco_pago,v_preco_balcao);
          END IF;
        END IF;

        IF v_item->>'sale_mode'='value' THEN
          v_sale_total := round(NULLIF(v_item->>'line_total_cents','')::numeric/100,2);
        ELSE
          v_sale_total := CASE WHEN v_quantity IS NOT NULL AND v_sale_unit_price IS NOT NULL
            THEN round(v_quantity*v_sale_unit_price,2) ELSE NULL END;
        END IF;
        v_cost_total := CASE WHEN v_quantity IS NOT NULL AND v_unit_cost IS NOT NULL
          THEN round(v_quantity*v_unit_cost,2) ELSE NULL END;

        IF FOUND AND v_has_existing THEN
          UPDATE feira_cost_private.order_item_snapshots
          SET product_name=v_product_name,quantity=v_quantity,sale_unit_price=v_sale_unit_price,
              sale_total=v_sale_total,cost_total=v_cost_total,
              unit_cost=v_unit_cost,
              profit=CASE WHEN v_sale_total IS NOT NULL AND v_cost_total IS NOT NULL THEN round(v_sale_total-v_cost_total,2) END,
              cost_status=CASE WHEN v_quantity IS NULL OR v_sale_unit_price IS NULL THEN 'invalid_item'
                               WHEN v_unit_cost IS NULL THEN 'missing_cost' ELSE 'ok' END,
              captured_at=now()
          WHERE order_id=NEW.id AND item_index=v_index;
        ELSE
          INSERT INTO feira_cost_private.order_item_snapshots(
            order_id,item_index,product_id,product_name,quantity,sale_unit_price,
            unit_cost,preco_balcao,preco_pago,sale_total,cost_total,profit,cost_status,captured_at
          ) VALUES (
            NEW.id,v_index,v_product_id,v_product_name,v_quantity,v_sale_unit_price,
            v_unit_cost,v_preco_balcao,v_preco_pago,v_sale_total,v_cost_total,
            CASE WHEN v_sale_total IS NOT NULL AND v_cost_total IS NOT NULL THEN round(v_sale_total-v_cost_total,2) END,
            CASE WHEN v_quantity IS NULL OR v_sale_unit_price IS NULL THEN 'invalid_item'
                 WHEN v_unit_cost IS NULL THEN 'missing_cost' ELSE 'ok' END,
            now()
          )
          ON CONFLICT(order_id,item_index) DO UPDATE SET
            product_id=EXCLUDED.product_id,product_name=EXCLUDED.product_name,quantity=EXCLUDED.quantity,
            sale_unit_price=EXCLUDED.sale_unit_price,unit_cost=EXCLUDED.unit_cost,
            preco_balcao=EXCLUDED.preco_balcao,preco_pago=EXCLUDED.preco_pago,
            sale_total=EXCLUDED.sale_total,cost_total=EXCLUDED.cost_total,profit=EXCLUDED.profit,
            cost_status=EXCLUDED.cost_status,captured_at=now();
        END IF;
      END LOOP;
      DELETE FROM feira_cost_private.order_item_snapshots
      WHERE order_id=NEW.id AND item_index>=v_item_count;
    ELSE
      DELETE FROM feira_cost_private.order_item_snapshots WHERE order_id=NEW.id;
    END IF;
  EXCEPTION WHEN OTHERS THEN
    GET STACKED DIAGNOSTICS v_error = MESSAGE_TEXT;
    -- The exception block rolls back its own partial writes; existing snapshots remain intact.
    BEGIN
      INSERT INTO feira_cost_private.snapshot_errors(order_id,error_message)
      VALUES(NEW.id,left(COALESCE(v_error,'Falha desconhecida na captura de custo'),500));
    EXCEPTION WHEN OTHERS THEN NULL;
    END;
  END;
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_get_order_profit(
  p_order_ids text[],
  p_start timestamptz,
  p_end timestamptz
) RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_result jsonb;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_current_user_admin() THEN
    RAISE EXCEPTION 'Acesso permitido somente a administradores.' USING ERRCODE='42501';
  END IF;
  IF p_start IS NULL OR p_end IS NULL OR p_end<=p_start THEN
    RAISE EXCEPTION 'Período inválido.' USING ERRCODE='22023';
  END IF;

  WITH target_orders AS MATERIALIZED (
    SELECT o.* FROM public.orders o
    WHERE o.id=ANY(COALESCE(p_order_ids,ARRAY[]::text[]))
       OR (o.created_at>=p_start AND o.created_at<p_end)
  ),
  order_finance AS (
    SELECT o.id,o.created_at,o.status,o.payment_method,o.total,
      COALESCE(o.is_test_order,false) is_test_order,
      COALESCE(i.items,'[]'::jsonb) items,
      COALESCE(i.calculated_items,0)::integer calculated_items,
      COALESCE(i.total_items,0)::integer total_items,
      COALESCE(i.missing_cost_items,0)::integer missing_cost_items,
      COALESCE(i.known_revenue,0)::numeric known_revenue,
      COALESCE(i.item_profit,0)::numeric item_profit,
      COALESCE(i.counter_profit,0)::numeric counter_profit,
      GREATEST(COALESCE(dc.actual_cost,0)-COALESCE(o.delivery_fee,0),0)::numeric delivery_covered,
      (COALESCE(i.item_profit,0)-GREATEST(COALESCE(dc.actual_cost,0)-COALESCE(o.delivery_fee,0),0))::numeric profit,
      (COALESCE(i.counter_profit,0)-GREATEST(COALESCE(dc.actual_cost,0)-COALESCE(o.delivery_fee,0),0))::numeric profit_on_counter
    FROM target_orders o
    LEFT JOIN feira_cost_private.order_delivery_costs dc ON dc.order_id=o.id
    LEFT JOIN LATERAL (
      SELECT
        jsonb_agg(jsonb_build_object(
          'item_index',(item.ordinality-1)::integer,
          'product_id',COALESCE(s.product_id,NULLIF(item.value->>'id','')),
          'product_name',COALESCE(s.product_name,NULLIF(item.value->>'name',''),'Produto sem nome'),
          'quantity',COALESCE(s.quantity,NULLIF(item.value->>'qty','')::numeric,NULLIF(item.value->>'quantity','')::numeric,1),
          'sale_unit_price',COALESCE(s.sale_unit_price,NULLIF(item.value->>'price','')::numeric),
          'unit_cost',COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost),
          'preco_balcao',COALESCE(s.preco_balcao,s.unit_cost),
          'preco_pago',s.preco_pago,
          'sale_total',COALESCE(s.sale_total,round(COALESCE(NULLIF(item.value->>'price','')::numeric,0)*COALESCE(NULLIF(item.value->>'qty','')::numeric,NULLIF(item.value->>'quantity','')::numeric,1),2)),
          'cost_total',CASE WHEN s.quantity IS NOT NULL AND COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost) IS NOT NULL THEN round(s.quantity*COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost),2) ELSE NULL END,
          'profit',CASE WHEN s.sale_total IS NOT NULL AND s.quantity IS NOT NULL AND COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost) IS NOT NULL THEN round(s.sale_total-s.quantity*COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost),2) ELSE NULL END,
          'profit_on_counter',CASE WHEN s.sale_total IS NOT NULL AND s.quantity IS NOT NULL AND COALESCE(s.preco_balcao,s.unit_cost) IS NOT NULL THEN round(s.sale_total-s.quantity*COALESCE(s.preco_balcao,s.unit_cost),2) ELSE NULL END,
          'cost_status',CASE WHEN COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost) IS NOT NULL THEN 'ok' ELSE COALESCE(s.cost_status,'missing_cost') END
        ) ORDER BY item.ordinality) items,
        count(*) FILTER(WHERE COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost) IS NOT NULL)::integer calculated_items,
        count(*)::integer total_items,
        count(*) FILTER(WHERE COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost) IS NULL)::integer missing_cost_items,
        COALESCE(sum(s.sale_total) FILTER(WHERE COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost) IS NOT NULL),0)::numeric known_revenue,
        COALESCE(sum(s.sale_total-s.quantity*COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost)) FILTER(WHERE s.sale_total IS NOT NULL AND s.quantity IS NOT NULL AND COALESCE(s.preco_pago,s.preco_balcao,s.unit_cost) IS NOT NULL),0)::numeric item_profit,
        COALESCE(sum(s.sale_total-s.quantity*COALESCE(s.preco_balcao,s.unit_cost)) FILTER(WHERE s.sale_total IS NOT NULL AND s.quantity IS NOT NULL AND COALESCE(s.preco_balcao,s.unit_cost) IS NOT NULL),0)::numeric counter_profit
      FROM jsonb_array_elements(CASE WHEN jsonb_typeof(COALESCE(o.items,'[]'::jsonb))='array' THEN COALESCE(o.items,'[]'::jsonb) ELSE '[]'::jsonb END)
        WITH ORDINALITY item(value,ordinality)
      LEFT JOIN feira_cost_private.order_item_snapshots s ON s.order_id=o.id AND s.item_index=(item.ordinality-1)::integer
    ) i ON true
  ),
  today_orders AS (SELECT * FROM order_finance WHERE created_at>=p_start AND created_at<p_end AND is_test_order=false),
  day_orders AS (SELECT * FROM today_orders WHERE lower(btrim(COALESCE(status,''))) NOT IN ('cancelada','cancelado','pagamento cancelado','pagamento recusado','pagamento reembolsado','pagamento contestado')),
  paid_day_orders AS (
    SELECT * FROM day_orders WHERE
      (lower(COALESCE(payment_method,'')) LIKE '%pix%' AND lower(btrim(COALESCE(status,''))) IN ('pagamento confirmado','preparando','pronto para retirada','saiu para entrega','entregue','pago','concluído','concluido'))
      OR (lower(COALESCE(payment_method,'')) NOT LIKE '%pix%' AND lower(btrim(COALESCE(status,''))) IN ('entregue','concluído','concluido'))
  )
  SELECT jsonb_build_object(
    'orders',COALESCE((SELECT jsonb_agg(jsonb_build_object(
      'order_id',f.id,'items',f.items,'calculated_items',f.calculated_items,'total_items',f.total_items,
      'missing_cost_items',f.missing_cost_items,'known_revenue',f.known_revenue,'item_profit',f.item_profit,
      'profit_on_counter',f.counter_profit,'delivery_covered',f.delivery_covered,'profit',f.profit,
      'profit_on_counter_total',f.profit_on_counter
    ) ORDER BY f.created_at DESC) FROM order_finance f),'[]'::jsonb),
    'summary',jsonb_build_object(
      'orders_today',(SELECT count(*)::integer FROM today_orders),
      'to_separate',(SELECT count(*)::integer FROM day_orders WHERE lower(btrim(COALESCE(status,''))) IN ('pagamento confirmado','preparando')),
      'in_delivery',(SELECT count(*)::integer FROM day_orders WHERE lower(btrim(COALESCE(status,'')))='saiu para entrega'),
      'paid_sales',(SELECT COALESCE(sum(total),0)::numeric FROM paid_day_orders),
      'profit',(SELECT COALESCE(sum(profit),0)::numeric FROM paid_day_orders),
      'profit_on_counter',(SELECT COALESCE(sum(profit_on_counter),0)::numeric FROM paid_day_orders),
      'missing_cost_items',(SELECT COALESCE(sum(missing_cost_items),0)::integer FROM paid_day_orders),
      'calculated_items',(SELECT COALESCE(sum(calculated_items),0)::integer FROM paid_day_orders),
      'total_items',(SELECT COALESCE(sum(total_items),0)::integer FROM paid_day_orders)
    )
  ) INTO v_result;
  RETURN v_result;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_get_cost_report_with_delivery(p_start timestamptz,p_end timestamptz)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
WITH paid_orders AS MATERIALIZED (
  SELECT o.id,o.delivery_type,o.delivery_fee
  FROM public.orders o
  WHERE o.created_at>=p_start AND o.created_at<p_end AND COALESCE(o.is_test_order,false)=false
    AND lower(btrim(COALESCE(o.status,''))) NOT IN ('cancelada','cancelado','pagamento cancelado','pagamento recusado','pagamento reembolsado','pagamento contestado')
    AND ((lower(COALESCE(o.payment_method,'')) LIKE '%pix%' AND lower(btrim(COALESCE(o.status,''))) IN ('pagamento confirmado','preparando','pronto para retirada','saiu para entrega','entregue','pago','concluido','concluído'))
      OR (lower(COALESCE(o.payment_method,'')) NOT LIKE '%pix%' AND lower(btrim(COALESCE(o.status,''))) IN ('entregue','concluido','concluído')))
), period_items AS (
  SELECT s.* FROM feira_cost_private.order_item_snapshots s JOIN paid_orders o ON o.id=s.order_id
), totals AS (
  SELECT count(DISTINCT order_id)::integer orders,
    COALESCE(sum(sale_total),0)::numeric sales_total,
    COALESCE(sum(sale_total) FILTER(WHERE COALESCE(preco_pago,preco_balcao,unit_cost) IS NOT NULL),0)::numeric known_revenue,
    COALESCE(sum(quantity*COALESCE(preco_pago,preco_balcao,unit_cost)) FILTER(WHERE quantity IS NOT NULL AND COALESCE(preco_pago,preco_balcao,unit_cost) IS NOT NULL),0)::numeric known_cost,
    COALESCE(sum(sale_total-quantity*COALESCE(preco_pago,preco_balcao,unit_cost)) FILTER(WHERE sale_total IS NOT NULL AND quantity IS NOT NULL AND COALESCE(preco_pago,preco_balcao,unit_cost) IS NOT NULL),0)::numeric profit,
    COALESCE(sum(sale_total-quantity*COALESCE(preco_balcao,unit_cost)) FILTER(WHERE sale_total IS NOT NULL AND quantity IS NOT NULL AND COALESCE(preco_balcao,unit_cost) IS NOT NULL),0)::numeric profit_on_counter,
    count(*) FILTER(WHERE COALESCE(preco_pago,preco_balcao,unit_cost) IS NULL)::integer missing_cost_items,
    count(*) FILTER(WHERE COALESCE(preco_pago,preco_balcao,unit_cost) IS NOT NULL)::integer calculated_items,
    count(*)::integer total_items,
    count(*) FILTER(WHERE cost_status='invalid_item')::integer invalid_items
  FROM period_items
), delivery_totals AS (
  SELECT COALESCE(sum(o.delivery_fee) FILTER(WHERE o.delivery_type='lalamove'),0)::numeric delivery_fee_revenue,
    COALESCE(sum(c.actual_cost),0)::numeric delivery_actual_cost
  FROM paid_orders o LEFT JOIN feira_cost_private.order_delivery_costs c ON c.order_id=o.id
)
SELECT jsonb_build_object(
 'summary',jsonb_build_object(
  'orders',totals.orders,'sales_total',totals.sales_total,'known_revenue',totals.known_revenue,'known_cost',totals.known_cost,
  'profit',totals.profit,'profit_on_counter',totals.profit_on_counter,
  'delivery_fee_revenue',delivery_totals.delivery_fee_revenue,'delivery_actual_cost',delivery_totals.delivery_actual_cost,
  'profit_after_delivery',totals.profit+delivery_totals.delivery_fee_revenue-delivery_totals.delivery_actual_cost,
  'profit_percent',CASE WHEN totals.known_revenue>0 THEN round(100*totals.profit/totals.known_revenue,2) ELSE NULL END,
  'missing_cost_items',totals.missing_cost_items,'calculated_items',totals.calculated_items,'total_items',totals.total_items,'invalid_items',totals.invalid_items
 ),
 'products',COALESCE((SELECT jsonb_agg(jsonb_build_object(
  'id',p.id,'name',p.name,'category',p.category,'price',p.price,'available',p.available,
  'unit_cost',pc.unit_cost,'preco_balcao',pc.preco_balcao,'preco_pago',pc.preco_pago,'updated_at',pc.updated_at
 ) ORDER BY p.name) FROM public.products p LEFT JOIN feira_cost_private.product_costs pc ON pc.product_id=p.id),'[]'::jsonb)
)
FROM totals CROSS JOIN delivery_totals
WHERE public.is_current_user_admin() AND p_start IS NOT NULL AND p_end IS NOT NULL AND p_end>p_start
$function$;

